import os
import sys
import json
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from email.mime.base import MIMEBase
from email import encoders

REPORT_FILE = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "test-report.json")

def send_email():
    if not os.path.exists(REPORT_FILE):
        print(f"[EMAIL] Test report not found at {REPORT_FILE}. Skipping email.")
        return

    with open(REPORT_FILE, "r", encoding="utf-8") as f:
        report = json.load(f)

    # Email configuration via environment variables
    smtp_host = os.environ.get("SMTP_HOST")
    smtp_port = int(os.environ.get("SMTP_PORT", 587))
    smtp_user = os.environ.get("SMTP_USER")
    smtp_pass = os.environ.get("SMTP_PASS")
    recipient = os.environ.get("REPORT_RECIPIENT_EMAIL", os.environ.get("NOTIFICATION_EMAIL", "sherazijaz5041@gmail.com"))

    if not smtp_host or not smtp_user or not smtp_pass:
        print("[EMAIL REPORT] Note: SMTP credentials (SMTP_HOST, SMTP_USER, SMTP_PASS) not configured in secrets/environment.")
        print(f"[EMAIL REPORT] Configured recipient: {recipient}")
        print("[EMAIL REPORT] To enable automated email sending, configure SMTP_HOST, SMTP_USER, SMTP_PASS in GitHub Secrets.")
        return

    commit_sha = report.get("commitSha", "unknown")
    overall = report.get("overallStatus", "UNKNOWN")
    summary = report.get("summary", {})
    repo = report.get("repository", "midterm-portal")
    run_id = report.get("pipelineRunId", "unknown")

    subject = f"[{overall}] DevOps CI Test Report - {repo} (Commit: {commit_sha[:7]})"

    # HTML Body
    status_color = "#10b981" if overall == "PASSED" else "#ef4444"
    tests_html = ""
    for t in report.get("tests", []):
        mark = "✓ PASS" if t.get("result") == "passed" else "✗ FAIL"
        color = "#10b981" if t.get("result") == "passed" else "#ef4444"
        error_html = f"<div style='color: #ef4444; font-size: 12px; margin-top: 4px;'>{t.get('failureMessage')}</div>" if t.get("failureMessage") else ""
        tests_html += f"""
        <div style="border-bottom: 1px solid #e2e8f0; padding: 8px 0;">
            <span style="color: {color}; font-weight: bold; margin-right: 8px;">[{mark}]</span>
            <strong>{t.get('name')}</strong>
            {error_html}
        </div>
        """

    html_content = f"""
    <html>
    <body style="font-family: Arial, sans-serif; background-color: #f8fafc; padding: 20px;">
        <div style="max-width: 600px; margin: 0 auto; background: #ffffff; border-radius: 8px; border: 1px solid #e2e8f0; padding: 24px;">
            <div style="background-color: {status_color}; color: #ffffff; padding: 12px 16px; border-radius: 6px; font-weight: bold; font-size: 18px;">
                DevOps CI Test Report: {overall}
            </div>
            <p style="margin-top: 16px; color: #475569;">
                Automated continuous integration pipeline execution completed for <strong>{repo}</strong>.
            </p>
            <table style="width: 100%; border-collapse: collapse; margin-bottom: 20px; font-size: 14px;">
                <tr><td style="padding: 6px 0; color: #64748b;">Repository:</td><td><strong>{repo}</strong></td></tr>
                <tr><td style="padding: 6px 0; color: #64748b;">Commit SHA:</td><td><code>{commit_sha}</code></td></tr>
                <tr><td style="padding: 6px 0; color: #64748b;">Pipeline Run ID:</td><td>{run_id}</td></tr>
                <tr><td style="padding: 6px 0; color: #64748b;">Test Summary:</td><td><strong>Total: {summary.get('total')} | Passed: {summary.get('passed')} | Failed: {summary.get('failed')}</strong></td></tr>
            </table>
            <h3 style="border-bottom: 2px solid #e2e8f0; padding-bottom: 8px; color: #1e293b;">Individual Test Results</h3>
            {tests_html}
            <p style="font-size: 12px; color: #94a3b8; margin-top: 24px;">
                Generated by CSC418 DevOps Midterm Automated CI Pipeline. Attached: test-report.json
            </p>
        </div>
    </body>
    </html>
    """

    msg = MIMEMultipart()
    msg["From"] = smtp_user
    msg["To"] = recipient
    msg["Subject"] = subject
    msg.attach(MIMEText(html_content, "html"))

    # Attach JSON report
    with open(REPORT_FILE, "rb") as f:
        attachment = MIMEBase("application", "json")
        attachment.set_payload(f.read())
        encoders.encode_base64(attachment)
        attachment.add_header("Content-Disposition", "attachment", filename="test-report.json")
        msg.attach(attachment)

    try:
        server = smtplib.SMTP(smtp_host, smtp_port)
        server.starttls()
        server.login(smtp_user, smtp_pass)
        server.send_message(msg)
        server.quit()
        print(f"[EMAIL REPORT] Successfully sent test report email to {recipient}!")
    except Exception as e:
        print(f"[EMAIL REPORT ERROR] Failed to send email: {e}")

if __name__ == "__main__":
    send_email()
